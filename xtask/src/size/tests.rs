use super::*;

fn file(path: &str, krate: &str, lines: usize) -> FileSize {
    FileSize {
        path: path.into(),
        krate: krate.into(),
        lines,
    }
}

fn allow(files: &[(&str, usize)], crates: &[(&str, usize)]) -> Allow {
    Allow {
        files: files.iter().map(|(k, v)| (k.to_string(), *v)).collect(),
        crates: crates.iter().map(|(k, v)| (k.to_string(), *v)).collect(),
    }
}

#[test]
fn allow_list_round_trips() {
    let a = allow(&[("crates/a/src/lib.rs", 612)], &[("a", 2100), ("b", 2500)]);
    assert_eq!(parse_allow(&render_allow(&a)).unwrap(), a);
    assert_eq!(
        parse_allow(&render_allow(&Allow::default())).unwrap(),
        Allow::default()
    );
}

#[test]
fn allow_list_errors_name_the_line() {
    let cases = [
        ("[files]\nfoo = 1\n", "double quotes"),
        ("[files]\n\"a\" = many\n", "not a number"),
        ("\"a\" = 1\n", "before a [files] or [crates] header"),
        ("[files]\n\"a\" = 1\n\"a\" = 2\n", "duplicate"),
        ("[files]\njunk\n", "expected"),
    ];
    for (text, needle) in cases {
        let err = parse_allow(text).unwrap_err();
        assert!(err.contains(needle), "{text:?} -> {err}");
        assert!(err.contains("line "), "{err}");
    }
}

#[test]
fn counts_lines_and_skips_generated_files() {
    assert_eq!(count_lines(""), Some(0));
    assert_eq!(count_lines("a\nb\n"), Some(2));
    assert_eq!(count_lines("a\nb"), Some(2));
    assert_eq!(count_lines("// Generated by build.rs\nfn a() {}\n"), None);
    assert_eq!(count_lines("// @generated\nfn a() {}\n"), None);
    // The marker only counts on the first line and in a comment.
    assert_eq!(count_lines("fn a() {}\n// Generated by hand\n"), Some(2));
    assert_eq!(count_lines("let s = \"Generated by\";\n"), Some(1));
}

#[test]
fn files_at_or_under_the_limit_pass() {
    let files = [file("a.rs", "x", MAX_FILE_LINES), file("b.rs", "x", 1)];
    assert!(check(&files, &Allow::default()).is_empty());
}

#[test]
fn a_file_over_the_limit_fails_unless_listed() {
    let files = [file("big.rs", "x", MAX_FILE_LINES + 1)];
    let v = check(&files, &Allow::default());
    assert_eq!(v.len(), 1);
    assert!(
        v[0].contains("big.rs") && v[0].contains("over the limit"),
        "{v:?}"
    );
    let listed = allow(&[("big.rs", MAX_FILE_LINES + 1)], &[]);
    assert!(check(&files, &listed).is_empty());
}

#[test]
fn a_listed_file_may_not_grow_or_stay_loose() {
    let listed = allow(&[("big.rs", 600)], &[]);
    let grew = check(&[file("big.rs", "x", 601)], &listed);
    assert!(
        grew.iter().any(|v| v.contains("grew from 600 to 601")),
        "{grew:?}"
    );
    let shrank = check(&[file("big.rs", "x", 550)], &listed);
    assert!(
        shrank.iter().any(|v| v.contains("shrank from 600 to 550")),
        "{shrank:?}"
    );
    let fixed = check(&[file("big.rs", "x", MAX_FILE_LINES)], &listed);
    assert!(fixed.iter().any(|v| v.contains("remove it")), "{fixed:?}");
    let gone = check(&[], &listed);
    assert!(
        gone.iter().any(|v| v.contains("does not exist")),
        "{gone:?}"
    );
}

#[test]
fn crates_are_summed_and_capped() {
    // Four files of MAX_FILE_LINES sum to exactly MAX_CRATE_LINES: allowed.
    let at_limit: Vec<_> = (0..4)
        .map(|i| file(&format!("a/{i}.rs"), "a", MAX_FILE_LINES))
        .collect();
    assert_eq!(MAX_FILE_LINES * 4, MAX_CRATE_LINES);
    assert!(check(&at_limit, &Allow::default()).is_empty());

    // One more line in a fifth file puts the crate over, while every file is still fine.
    let mut over = at_limit.clone();
    over.push(file("a/4.rs", "a", 1));
    let v = check(&over, &Allow::default());
    assert_eq!(v.len(), 1, "{v:?}");
    assert!(v[0].contains("crate `a`") && v[0].contains("2001"), "{v:?}");

    // Another crate with the same files is counted on its own.
    over.push(file("b/0.rs", "b", MAX_FILE_LINES));
    assert_eq!(check(&over, &Allow::default()).len(), 1);

    let listed = allow(&[], &[("a", MAX_CRATE_LINES + 1)]);
    assert!(check(&over, &listed).is_empty());
    let totals = crate_totals(&over);
    assert_eq!(totals["a"].lines, MAX_CRATE_LINES + 1);
    assert_eq!(totals["a"].files, 5);
    assert_eq!(totals["a"].largest.1, MAX_FILE_LINES);
}

#[test]
fn update_tightens_and_drops_but_never_raises() {
    let old = allow(&[("big.rs", 700), ("fixed.rs", 520)], &[]);
    let files = [file("big.rs", "x", 650), file("fixed.rs", "x", 400)];
    let next = next_allow(&files, &old).unwrap();
    assert_eq!(next, allow(&[("big.rs", 650)], &[]));

    let grew = next_allow(&[file("big.rs", "x", 701), file("fixed.rs", "x", 1)], &old).unwrap_err();
    assert!(
        grew.iter()
            .any(|r| r.contains("big.rs") && r.contains("never goes up")),
        "{grew:?}"
    );

    let new = next_allow(
        &[file("new.rs", "x", MAX_FILE_LINES + 1)],
        &Allow::default(),
    )
    .unwrap_err();
    assert!(new.iter().any(|r| r.contains("not in the list")), "{new:?}");
}

#[test]
fn collect_skips_target_vendor_hidden_generated_and_other_extensions() {
    let root = std::env::temp_dir().join(format!("xtask-size-{}", std::process::id()));
    let _ = fs::remove_dir_all(&root);
    let write = |path: &str, text: &str| {
        let full = root.join(path);
        fs::create_dir_all(full.parent().unwrap()).unwrap();
        fs::write(full, text).unwrap();
    };
    write("crates/a/src/lib.rs", "a\nb\nc\n");
    write("crates/a/tests/it.rs", "x\n");
    write("crates/a/target/debug/build.rs", "no\n");
    write("crates/a/vendor/dep/lib.rs", "no\n");
    write("crates/a/.hidden/x.rs", "no\n");
    write("crates/a/src/gen.rs", "// Generated by tool\nfn x() {}\n");
    write("crates/a/src/readme.md", "no\n");
    write("crates/a/inner/src/lib.rs", "i\nj\n");
    write("spikes/s/src/main.rs", "not in a root\n");
    // A symlink to a directory that points back up would loop; a symlinked file is not ours.
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(root.join("crates"), root.join("crates/a/src/loop")).unwrap();
        std::os::unix::fs::symlink(
            root.join("spikes/s/src/main.rs"),
            root.join("crates/a/src/link.rs"),
        )
        .unwrap();
    }
    let crates = vec![
        ("a".to_string(), root.join("crates/a")),
        ("inner".to_string(), root.join("crates/a/inner")),
    ];
    let files = collect(&root, &crates).unwrap();
    let got: Vec<_> = files
        .iter()
        .map(|f| (f.path.as_str(), f.krate.as_str(), f.lines))
        .collect();
    assert_eq!(
        got,
        [
            ("crates/a/inner/src/lib.rs", "inner", 2),
            ("crates/a/src/lib.rs", "a", 3),
            ("crates/a/tests/it.rs", "a", 1),
        ]
    );
    let _ = fs::remove_dir_all(&root);
}
