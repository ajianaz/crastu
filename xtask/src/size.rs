//! `cargo xtask size-check`: caps on lines per file and per crate.
//!
//! A file over [`MAX_FILE_LINES`] or a crate over [`MAX_CRATE_LINES`] must be listed in
//! `xtask/size-allow.toml` with its size today. An entry is a ceiling that only moves down:
//! growing past it fails, and shrinking below it fails until `--update` tightens it, so the
//! list can only get shorter or smaller. `--update` itself refuses to raise or add anything.
//!
//! ```text
//! cargo xtask size-check            check the limits
//! cargo xtask size-check --report   print every crate: lines, files, largest file
//! cargo xtask size-check --update   tighten the allow-list (never raises it)
//! ```

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::Value;

pub const MAX_FILE_LINES: usize = 500;
pub const MAX_CRATE_LINES: usize = 2000;
const ROOTS: &[&str] = &["crates", "apps", "xtask"];
const ALLOW_FILE: &str = "xtask/size-allow.toml";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileSize {
    /// Path relative to the workspace root, with `/` separators.
    pub path: String,
    pub krate: String,
    pub lines: usize,
}

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Allow {
    pub files: BTreeMap<String, usize>,
    pub crates: BTreeMap<String, usize>,
}

#[derive(Debug, PartialEq, Eq)]
pub struct CrateSize {
    pub lines: usize,
    pub files: usize,
    pub largest: (String, usize),
}

/// Parses the allow-list, a strict subset of TOML: `[files]` and `[crates]` tables whose
/// entries look like `"name" = 123`, plus `#` comment lines.
pub fn parse_allow(text: &str) -> Result<Allow, String> {
    let mut allow = Allow::default();
    let mut section: Option<&str> = None;
    for (i, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let at = format!("{ALLOW_FILE} line {}", i + 1);
        match line {
            "[files]" => section = Some("files"),
            "[crates]" => section = Some("crates"),
            _ => {
                let (key, value) = line
                    .split_once('=')
                    .ok_or_else(|| format!("{at}: expected `\"name\" = lines`"))?;
                let key = key
                    .trim()
                    .strip_prefix('"')
                    .and_then(|k| k.strip_suffix('"'))
                    .ok_or_else(|| format!("{at}: the name must be in double quotes"))?;
                let value: usize = value
                    .trim()
                    .parse()
                    .map_err(|_| format!("{at}: `{}` is not a number", value.trim()))?;
                let table = match section {
                    Some("files") => &mut allow.files,
                    Some("crates") => &mut allow.crates,
                    _ => return Err(format!("{at}: entry before a [files] or [crates] header")),
                };
                if table.insert(key.to_string(), value).is_some() {
                    return Err(format!("{at}: duplicate entry `{key}`"));
                }
            }
        }
    }
    Ok(allow)
}

pub fn render_allow(allow: &Allow) -> String {
    let mut out = String::from(
        "# Files and crates allowed over the size limits (see `cargo xtask size-check`).\n\
         # A size is a ceiling that only moves down; `cargo xtask size-check --update` tightens it.\n",
    );
    for (title, table) in [("files", &allow.files), ("crates", &allow.crates)] {
        out.push_str(&format!("\n[{title}]\n"));
        for (name, lines) in table {
            out.push_str(&format!("\"{name}\" = {lines}\n"));
        }
    }
    out
}

/// Line count of a source file, or `None` for a generated file (its first line says so).
pub fn count_lines(text: &str) -> Option<usize> {
    let first = text.lines().next().unwrap_or("").to_ascii_lowercase();
    if first.starts_with("//") && (first.contains("@generated") || first.contains("generated by")) {
        return None;
    }
    Some(text.lines().count())
}

pub fn crate_totals(files: &[FileSize]) -> BTreeMap<String, CrateSize> {
    let mut totals: BTreeMap<String, CrateSize> = BTreeMap::new();
    for f in files {
        let entry = totals.entry(f.krate.clone()).or_insert_with(|| CrateSize {
            lines: 0,
            files: 0,
            largest: (String::new(), 0),
        });
        entry.lines += f.lines;
        entry.files += 1;
        if f.lines > entry.largest.1 {
            entry.largest = (f.path.clone(), f.lines);
        }
    }
    totals
}

fn judge(
    out: &mut Vec<String>,
    what: &str,
    name: &str,
    lines: usize,
    limit: usize,
    ceiling: Option<usize>,
) {
    match ceiling {
        None if lines > limit => {
            out.push(format!("{what} `{name}` has {lines} lines, over the limit of {limit}"));
        }
        None => {}
        Some(ceiling) if lines > ceiling => out.push(format!(
            "{what} `{name}` grew from {ceiling} to {lines} lines (limit {limit})"
        )),
        Some(_) if lines <= limit => out.push(format!(
            "{what} `{name}` is {lines} lines, within the limit of {limit}: remove it from the allow-list with `cargo xtask size-check --update`"
        )),
        Some(ceiling) if lines < ceiling => out.push(format!(
            "{what} `{name}` shrank from {ceiling} to {lines} lines: lower its ceiling with `cargo xtask size-check --update`"
        )),
        Some(_) => {}
    }
}

/// Every way the current sizes break the limits or the allow-list. Empty means pass.
pub fn check(files: &[FileSize], allow: &Allow) -> Vec<String> {
    let mut out = Vec::new();
    let totals = crate_totals(files);
    for f in files {
        let ceiling = allow.files.get(&f.path).copied();
        judge(&mut out, "file", &f.path, f.lines, MAX_FILE_LINES, ceiling);
    }
    for (name, t) in &totals {
        let ceiling = allow.crates.get(name).copied();
        judge(&mut out, "crate", name, t.lines, MAX_CRATE_LINES, ceiling);
    }
    for path in allow.files.keys() {
        if !files.iter().any(|f| &f.path == path) {
            out.push(format!("file `{path}` is in the allow-list but does not exist: run `cargo xtask size-check --update`"));
        }
    }
    for name in allow.crates.keys() {
        if !totals.contains_key(name) {
            out.push(format!("crate `{name}` is in the allow-list but has no sources: run `cargo xtask size-check --update`"));
        }
    }
    out
}

fn tighten(
    what: &str,
    name: &str,
    lines: usize,
    limit: usize,
    old: Option<usize>,
    table: &mut BTreeMap<String, usize>,
    refused: &mut Vec<String>,
) {
    if lines <= limit {
        return;
    }
    match old {
        Some(ceiling) if lines <= ceiling => {
            table.insert(name.to_string(), lines);
        }
        Some(ceiling) => refused.push(format!(
            "{what} `{name}` grew from {ceiling} to {lines} lines: shrink it, the list never goes up"
        )),
        None => refused.push(format!(
            "{what} `{name}` has {lines} lines, over the limit of {limit}, and is not in the list: split it, new entries are not added"
        )),
    }
}

/// The allow-list for the current sizes: every entry kept at its new size or dropped once it
/// is back within the limit. Refuses (with the reasons) when anything would go up or be added.
pub fn next_allow(files: &[FileSize], old: &Allow) -> Result<Allow, Vec<String>> {
    let (mut next, mut refused) = (Allow::default(), Vec::new());
    for f in files {
        let ceiling = old.files.get(&f.path).copied();
        tighten(
            "file",
            &f.path,
            f.lines,
            MAX_FILE_LINES,
            ceiling,
            &mut next.files,
            &mut refused,
        );
    }
    for (name, t) in &crate_totals(files) {
        let ceiling = old.crates.get(name).copied();
        tighten(
            "crate",
            name,
            t.lines,
            MAX_CRATE_LINES,
            ceiling,
            &mut next.crates,
            &mut refused,
        );
    }
    if refused.is_empty() {
        Ok(next)
    } else {
        Err(refused)
    }
}

fn is_skipped_dir(name: &str) -> bool {
    name == "target" || name == "vendor" || name.starts_with('.')
}

pub(crate) fn walk(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| e.to_string())?;
        let file_type = entry.file_type().map_err(|e| e.to_string())?;
        let path = entry.path();
        if file_type.is_symlink() {
            continue;
        }
        if file_type.is_dir() {
            if !is_skipped_dir(&entry.file_name().to_string_lossy()) {
                walk(&path, out)?;
            }
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
    Ok(())
}

/// Sizes of every non-generated `.rs` file under the source roots, each assigned to the crate
/// whose directory is its closest parent.
pub fn collect(root: &Path, crates: &[(String, PathBuf)]) -> Result<Vec<FileSize>, String> {
    let mut paths = Vec::new();
    for dir in ROOTS {
        let dir = root.join(dir);
        if dir.is_dir() {
            walk(&dir, &mut paths)?;
        }
    }
    paths.sort();
    let mut files = Vec::new();
    for path in paths {
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let Some(lines) = count_lines(&text) else {
            continue;
        };
        let owner = crates
            .iter()
            .filter(|(_, dir)| path.starts_with(dir))
            .max_by_key(|(_, dir)| dir.components().count())
            .ok_or_else(|| format!("{} belongs to no crate", path.display()))?;
        let relative = path.strip_prefix(root).unwrap_or(&path);
        files.push(FileSize {
            path: relative.to_string_lossy().replace('\\', "/"),
            krate: owner.0.clone(),
            lines,
        });
    }
    Ok(files)
}

fn print_report(files: &[FileSize]) {
    let mut rows: Vec<_> = crate_totals(files).into_iter().collect();
    rows.sort_by(|a, b| b.1.lines.cmp(&a.1.lines).then_with(|| a.0.cmp(&b.0)));
    println!(
        "{:<28} {:>6} {:>6}  largest file",
        "crate", "lines", "files"
    );
    for (name, t) in rows {
        println!(
            "{name:<28} {:>6} {:>6}  {} ({})",
            t.lines, t.files, t.largest.0, t.largest.1
        );
    }
}

pub fn run(args: &[String], meta: &Value) -> Result<(), String> {
    let (mut update, mut report) = (false, false);
    for arg in args {
        match arg.as_str() {
            "--update" => update = true,
            "--report" => report = true,
            other => return Err(format!("unknown option {other}; use --report or --update")),
        }
    }
    let root = PathBuf::from(meta["workspace_root"].as_str().ok_or("no workspace_root")?);
    let crates: Vec<(String, PathBuf)> = meta["packages"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|p| {
            let dir = Path::new(p["manifest_path"].as_str()?)
                .parent()?
                .to_path_buf();
            Some((p["name"].as_str()?.to_string(), dir))
        })
        .collect();
    let files = collect(&root, &crates)?;
    if report {
        print_report(&files);
        return Ok(());
    }
    let allow_path = root.join(ALLOW_FILE);
    let allow = match fs::read_to_string(&allow_path) {
        Ok(text) => parse_allow(&text)?,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Allow::default(),
        Err(e) => return Err(format!("{ALLOW_FILE}: {e}")),
    };
    if update {
        let next = next_allow(&files, &allow).map_err(|r| r.join("\n"))?;
        if next == allow && allow_path.exists() {
            println!("size-check: the allow-list is already tight");
        } else {
            fs::write(&allow_path, render_allow(&next)).map_err(|e| e.to_string())?;
            println!("size-check: wrote {ALLOW_FILE}");
        }
        return Ok(());
    }
    let violations = check(&files, &allow);
    if violations.is_empty() {
        println!(
            "size-check: {} files, {} crates within {MAX_FILE_LINES} lines per file and {MAX_CRATE_LINES} per crate",
            files.len(),
            crate_totals(&files).len()
        );
        return Ok(());
    }
    for v in &violations {
        println!("violation: {v}");
    }
    Err(format!("{} size violation(s)", violations.len()))
}

